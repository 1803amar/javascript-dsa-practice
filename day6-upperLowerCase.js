function toUpper(str) {
  return str.toUpperCase();
}

function toLower(str) {
  return str.toLowerCase();
}

console.log(toUpper("hello world"));  // "HELLO WORLD"
console.log(toLower("HELLO WORLD"));  // "hello world"

// .toUpperCase is used to convert in upper case the string/str
// .toLowerCase is used to convert in lower case the string/str